def _bump(num):
    """Change a figure to a clearly different one, keeping its shape so the
    sentence still reads naturally."""
    clean = num.replace(",", "")
    try:
        v = float(clean)
    except ValueError:
        return None
    new = int(v * 3) + 7 if v else 42
    if "." in clean:
        return f"{v * 3 + 7:.1f}"
    return f"{new:,}" if "," in num else str(new)
